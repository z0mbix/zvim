"""Generate the tap cask from a verified, published macOS release archive."""
import argparse
import hashlib
import json
from pathlib import Path

from version import SEMVER


def stable_version(tag):
    value = tag.removeprefix("v")
    match = SEMVER.fullmatch(value)
    if not tag.startswith("v") or match is None or match.group(4) is not None:
        raise ValueError("Homebrew requires a stable SemVer tag prefixed with v")
    return value


def validate_release(tag, release, latest_tag):
    stable_version(tag)
    if release["isDraft"] or release["isPrerelease"] or release["tagName"] != tag:
        raise ValueError("Homebrew requires a published stable release matching the tag")
    if tag != latest_tag:
        raise ValueError(f"Refusing to replace the tap with an older release; latest is {latest_tag}")


def homebrew_cask(tag, directory):
    version = stable_version(tag)
    checksums = {}
    for line in (directory / "SHA256SUMS.txt").read_text().splitlines():
        digest, filename = line.split()
        if filename in checksums:
            raise ValueError(f"Duplicate checksum for {filename}")
        checksums[filename] = digest

    filename = f"zvim-{tag}-macos-arm64.zip"
    digest = hashlib.sha256((directory / filename).read_bytes()).hexdigest()
    if checksums.get(filename) != digest:
        raise ValueError(f"Missing or mismatched checksum for {filename}")

    return f'''# Generated by z0mbix/zvim scripts/homebrew_cask.py.
cask "zvim" do
  version "{version}"
  sha256 "{digest}"

  url "https://github.com/z0mbix/zvim/releases/download/v#{{version}}/zvim-v#{{version}}-macos-arm64.zip"
  name "Zvim"
  desc "Native Neovim frontend with an integrated Ghostty terminal"
  homepage "https://github.com/z0mbix/zvim"

  depends_on arch: :arm64
  depends_on macos: :ventura

  app "Zvim.app"
end
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    validate = commands.add_parser("validate", help="Require the latest published stable release")
    validate.add_argument("tag")
    validate.add_argument("release_json", type=Path)
    validate.add_argument("latest_tag")
    generate = commands.add_parser("generate", help="Verify the archive and write its cask")
    generate.add_argument("tag")
    generate.add_argument("release_directory", type=Path)
    generate.add_argument("output", type=Path)
    args = parser.parse_args()

    if args.command == "validate":
        validate_release(args.tag, json.loads(args.release_json.read_text()), args.latest_tag)
    else:
        cask = homebrew_cask(args.tag, args.release_directory)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(cask)


if __name__ == "__main__":
    main()
